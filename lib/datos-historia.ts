export function obtenerMomentosPorAnio(
  anio: 2025 | 2026
) {
  return historiaCompleta.filter(
    (momento) => momento.anio === anio
  );
}

export function obtenerMomentoHistoria(
  busqueda: string
) {
  const buscado = busqueda
    .trim()
    .toLowerCase();

  return historiaCompleta.find((momento) => {
    return (
      momento.titulo
        .toLowerCase()
        .includes(buscado) ||
      momento.subtitulo
        .toLowerCase()
        .includes(buscado) ||
      momento.fecha
        .toLowerCase()
        .includes(buscado) ||
      buscado.includes(
        momento.titulo.toLowerCase()
      )
    );
  });
}